static_assert(kHddTable.size() == 127, "the 128th row is the table's zero end marker");

consteval bool every_row_fits_the_table_product() {
    constexpr std::uint64_t kTwoTo32 = 1ULL << 32;
    for (const svc::DiskGeometry& row : kHddTable)
        if (row.bytes() >= proto::FileSize{kTwoTo32})
            return false;
    return true;
}

static_assert(every_row_fits_the_table_product());

[[nodiscard]] constexpr std::optional<svc::DiskGeometry> hdd_shape_of_size(
    proto::FileSize bytes
) noexcept {
    for (const svc::DiskGeometry& row : kHddTable)
        if (row.bytes() == bytes)
            return row;
    return std::nullopt;
}

