CharSet CharSet::stock() noexcept {
    static_assert(kStockFont.size() + kStockFont.size() == GlyphSlot::count() * PixelLine::count());
    CharSet set;
    const std::span<std::byte> image = std::as_writable_bytes(std::span(set.glyphs_));
    const std::span<const std::byte> font = std::as_bytes(std::span(kStockFont));
    std::ranges::copy(font, image.begin());
    std::ranges::copy(font, image.subspan(font.size()).begin());
    return set;
}

