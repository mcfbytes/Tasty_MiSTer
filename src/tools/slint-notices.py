#!/usr/bin/env python3
"""Write the notices for the Rust crates linked into the static Slint archive.

    slint-notices.py <patched slint source> <out.md>

The crate set is cargo's for the archive build-static-slint.sh makes: slint-cpp, no default features,
renderer-software + std, armv7-unknown-linux-gnueabihf, normal edges, no proc-macros (those run in the
compiler and are not linked). Each crate's own licence files are copied verbatim, one copy per distinct
text; a crate that ships none is listed under its SPDX expression.
"""
from __future__ import annotations

import hashlib
import json
import os
import re
import subprocess
import sys
from pathlib import Path

TARGET = "armv7-unknown-linux-gnueabihf"
FEATURES = "renderer-software,std"
LICENCE_FILE = re.compile(r"^(licen[cs]e|copying|notice|unlicense)([-_.].*)?$", re.I)
MIT_TEXT = """Permission is hereby granted, free of charge, to any person obtaining a copy of this software and
associated documentation files (the "Software"), to deal in the Software without restriction, including
without limitation the rights to use, copy, modify, merge, publish, distribute, sublicense, and/or sell
copies of the Software, and to permit persons to whom the Software is furnished to do so, subject to the
following conditions:

The above copyright notice and this permission notice shall be included in all copies or substantial
portions of the Software.

THE SOFTWARE IS PROVIDED "AS IS", WITHOUT WARRANTY OF ANY KIND, EXPRESS OR IMPLIED, INCLUDING BUT NOT
LIMITED TO THE WARRANTIES OF MERCHANTABILITY, FITNESS FOR A PARTICULAR PURPOSE AND NONINFRINGEMENT. IN NO
EVENT SHALL THE AUTHORS OR COPYRIGHT HOLDERS BE LIABLE FOR ANY CLAIM, DAMAGES OR OTHER LIABILITY, WHETHER
IN AN ACTION OF CONTRACT, TORT OR OTHERWISE, ARISING FROM, OUT OF OR IN CONNECTION WITH THE SOFTWARE OR THE
USE OR OTHER DEALINGS IN THE SOFTWARE."""


def rust_pin() -> str:
    """build-static-slint.sh's Rust pin: the toolchain the archive (and so this crate set) is built with."""
    script = (Path(__file__).resolve().parent / "build-static-slint.sh").read_text(encoding="utf-8")
    m = re.search(r"^RUST_TOOLCHAIN=\$\{RUST_TOOLCHAIN:-([^}]+)\}", script, re.M)
    if m is None:
        raise SystemExit("build-static-slint.sh: no RUST_TOOLCHAIN pin")
    return m.group(1)


def cargo(src: Path, *args: str) -> str:
    env = dict(os.environ)
    env.setdefault("RUSTUP_TOOLCHAIN", rust_pin())
    return subprocess.run(["cargo", *args], cwd=src, env=env, check=True, capture_output=True,
                          text=True).stdout


def linked_crates(src: Path) -> list[tuple[str, str]]:
    out = cargo(src, "tree", "--locked", "-p", "slint-cpp", "--no-default-features", "--features", FEATURES,
                "--target", TARGET, "-e", "normal,no-proc-macro", "--prefix", "none", "--format", "{p}")
    seen: set[tuple[str, str]] = set()
    for line in out.splitlines():
        m = re.match(r"^(\S+) v(\S+)", line.strip())
        if m:
            seen.add((m.group(1), m.group(2)))
    return sorted(seen)


def licence_files(root: Path) -> list[Path]:
    files = [p for p in root.iterdir() if p.is_file() and LICENCE_FILE.match(p.name)]
    lic_dir = root / "LICENSES"
    if lic_dir.is_dir():
        files += [p for p in lic_dir.iterdir() if p.is_file()]
    return sorted(files)


def main() -> int:
    if len(sys.argv) != 3:
        print(__doc__, file=sys.stderr)
        return 2
    src, out = Path(sys.argv[1]).resolve(), Path(sys.argv[2])
    crates = linked_crates(src)
    meta = json.loads(cargo(src, "metadata", "--locked", "--format-version", "1", "--filter-platform", TARGET))
    pkgs = {(p["name"], p["version"]): p for p in meta["packages"]}
    texts: dict[str, tuple[str, str, list[str]]] = {}  # sha -> (file name, text, crates)
    bare: dict[str, list[str]] = {}
    bare_mit: list[str] = []  # "crate ver: Copyright (c) authors"
    rows: list[str] = []
    for name, ver in crates:
        pkg = pkgs[(name, ver)]
        spdx = pkg.get("license") or "see licence file"
        rows.append(f"| {name} | {ver} | {spdx} |")
        files = licence_files(Path(pkg["manifest_path"]).parent)
        if not files:
            bare.setdefault(spdx, []).append(f"{name} {ver}")
            if re.search(r"\bMIT\b", spdx):
                who = ", ".join(pkg.get("authors") or []) or f"the {name} authors"
                bare_mit.append(f"{name} {ver}: Copyright (c) {who}")
        for f in files:
            text = f.read_text(encoding="utf-8", errors="replace").replace("\r\n", "\n").strip("\n")
            h = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(h, (f.name, text, []))[2].append(f"{name} {ver}")
    lines = [
        "# Rust crates in the static Slint archive",
        "",
        f"Generated by `src/tools/slint-notices.py` from the patched Slint source: crate `slint-cpp`, features "
        f"`{FEATURES}`, target `{TARGET}`, {len(crates)} crates.",
        "",
        "| crate | version | licence |",
        "|---|---|---|",
        *rows,
        "",
    ]
    if bare:
        lines += ["## Crates that ship no licence file", "",
                  "Each is distributed under the standard text of the licence its manifest names.", ""]
        for spdx in sorted(bare):
            lines.append(f"- {spdx}: {', '.join(sorted(bare[spdx]))}")
        lines.append("")
    if bare_mit:
        lines += ["### The MIT licence, for those of them offered under it", "",
                  "Each crate's copyright line, from its manifest's `authors`:", "",
                  *(f"- {c}" for c in sorted(bare_mit)), "", "```text", MIT_TEXT, "```", ""]
    lines += ["## Licence texts", ""]
    for h, (fname, text, users) in sorted(texts.items(), key=lambda kv: (sorted(kv[1][2])[0], kv[1][0])):
        lines += [f"### {fname}: {', '.join(sorted(users))}", "", "```text", text, "```", ""]
    out.write_text("\n".join(lines), encoding="utf-8")
    print(f"{out}: {len(crates)} crates, {len(texts)} distinct texts, {sum(map(len, bare.values()))} without a file")
    return 0


if __name__ == "__main__":
    sys.exit(main())
