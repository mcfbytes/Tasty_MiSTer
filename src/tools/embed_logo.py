#!/usr/bin/env python3
"""Decode art/logo.png into the front-end logo's RGBA table (WO-M3).

The generator reuses the tasty splash decoder: one PNG reader in the tree, so the logo and
the splash cannot disagree about what a PNG chunk means. The output is a generated `.cpp`
holding one `const std::uint8_t` table plus its pins (the PNG's SHA-256 and the decoded
bytes' CRC-32); the unit test asserts both against `app/front_end_logo.h`.
"""
from __future__ import annotations

import argparse
import hashlib
import sys
import zlib
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
sys.path.insert(1, str(Path(__file__).resolve().parent.parent / "tasty-export"))
from embed_splash import decode_png  # noqa: E402

# art/logo.png is 480x192; app/front_end_logo.h fixes the same two counts.
width = 480
height = 192
bytes_per_pixel = 4


def write_table(png: Path, dest: Path) -> None:
    data = png.read_bytes()
    w, h, rgba = decode_png(data)
    if (w, h) != (width, height):
        raise SystemExit(f"{png}: {w}x{h}, art/logo.png must stay {width}x{height}")
    if len(rgba) != width * height * bytes_per_pixel:
        raise SystemExit(f"{png}: decoded {len(rgba)} bytes, expected {width * height * 4}")
    # One `LogoPixel` per entry, red first: the table is the app's own value type, and the pixel's
    # four bytes are the PNG's, so the CRC-32 below is computed over the same bytes.
    body = "\n".join(
        "LogoPixel{{" + ",".join(f"0x{rgba[i + j]:02x}" for j in range(bytes_per_pixel)) + "}},"
        for i in range(0, len(rgba), bytes_per_pixel)
    )
    dest.write_text(
        "// Generated by embed_logo.py from the logo PNG. Do not edit.\n"
        '#include "app/front_end_logo.h"\n'
        "\n"
        "namespace mister::app {\n"
        "\n"
        "extern const LogoArt kLogoArt = {\n"
        "{\n"
        f"{body}\n"
        "}\n"
        "};\n"
        "\n"
        f"extern const svc::Crc32 kLogoRgbaCrc32 = svc::Crc32{{0x{zlib.crc32(rgba):08x}u}};\n"
        "\n"
        f'extern const char kLogoPngSha256[65] = "{hashlib.sha256(data).hexdigest()}";\n'
        "\n"
        "}  // namespace mister::app\n"
    )


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("png")
    ap.add_argument("cpp")
    args = ap.parse_args()
    write_table(Path(args.png), Path(args.cpp))
    return 0


if __name__ == "__main__":
    sys.exit(main())
